defmodule Aesir.ZoneServer.Content.Npc.Functions.FIsequipidhack do
  @moduledoc """
  Transpiled from rAthena other/Global_Functions.txt:394 (F_IsEquipIDHack).

  Regenerated by `mix aesir.import.npcs`; hand edits are detected through
  the transpile manifest and future imports land in `_conflicts/` instead
  of overwriting them.
  """

  import Aesir.ZoneServer.Script.Dsl, warn: false
  alias Aesir.ZoneServer.Script.Rathena

  @doc "Callable rAthena global function; returns `{ctx, return_value}`."
  def call(ctx, args) do
    try do
      ctx =
        ctx
        |> set_local(:id_chk, getequipid(ctx, Enum.at(args, 0, 0)))
        |> set_local(:id, Enum.at(args, 1, 0))

      ctx =
        if get_local(ctx, :id, 0) != get_local(ctx, :id_chk, 0) do
          ctx =
            logmes(
              ctx,
              Rathena.concat(
                Rathena.concat(
                  Rathena.concat(
                    Rathena.concat(
                      "Hack: Tried to swap equip ",
                      Rathena.getitemname(get_local(ctx, :id, 0))
                    ),
                    " for "
                  ),
                  Rathena.getitemname(get_local(ctx, :id_chk, 0))
                ),
                "."
              )
            )

          throw({:script_return, {ctx, 1}})
        else
          ctx
        end

      throw({:script_return, {ctx, 0}})
    catch
      :throw, {:script_return, result} -> result
    end
  end
end
