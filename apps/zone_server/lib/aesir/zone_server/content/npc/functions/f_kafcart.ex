        if count_item(ctx, 7061) > 0 and Enum.at(args, 0, 0) != 2 do
          delitem(ctx, 7061, 1)
        else
          ctx =
            ctx
            |> set_local(:rental_fee, Enum.at(args, 1, 0))
            |> mes("[Kafra Employee]")
            |> mes("The Pushcart rental")

          {ctx, v1} =
            ctx
            |> mes(
              Rathena.concat(
                Rathena.concat("fee is ", get_local(ctx, :rental_fee, 0)),
                " zeny. Would"
