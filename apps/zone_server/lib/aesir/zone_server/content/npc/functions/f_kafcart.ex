              throw({:script_return, {ctx, 0}})
            else
              ctx
            end

          ctx =
            if zeny(ctx) < get_local(ctx, :rental_fee, 0) do
              ctx =
                ctx
                |> mes("[Kafra Employee]")
                |> mes("I'm sorry, but you")
                |> mes("don't have enough")
                |> mes("zeny to pay the Pushcart")

              ctx =
                mes(
                  ctx,
