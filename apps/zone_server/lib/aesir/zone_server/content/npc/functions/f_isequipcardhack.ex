  @doc "Callable rAthena global function; returns `{ctx, return_value}`."
  def call(ctx, args) do
    try do
      ctx = ctx |> set_local(:pos, Enum.at(args, 0, 0)) |> set_local(:i, 0) |> loop_1(args)
      throw({:script_return, {ctx, 0}})
    catch
      :throw, {:script_return, result} -> result
    end
  end

  defp loop_1(ctx, args) do
    if get_local(ctx, :i, 0) < 4 do
      ctx = set_local(ctx, :card, Enum.at(args, get_local(ctx, :i, 0) + 1, 0))

      ctx =
        set_local(
          ctx,
          :card_chk,
          getequipcardid(ctx, get_local(ctx, :pos, 0), get_local(ctx, :i, 0))
        )

      ctx =
        if get_local(ctx, :card, 0) != get_local(ctx, :card_chk, 0) do
          ctx =
            todo(ctx, :logmes, [
              Rathena.concat(
                Rathena.concat(
                  Rathena.concat(
                    Rathena.concat(
                      "Hack: Tried to swap card ",
                      Todo.call!(:getitemname, [get_local(ctx, :card, 0)])
                    ),
                    " for "
                  ),
                  Todo.call!(:getitemname, [get_local(ctx, :card_chk, 0)])
                ),
                "."
              )
            ])

          throw({:script_return, {ctx, 1}})
        else
          ctx
        end

      ctx |> set_local(:i, get_local(ctx, :i, 0) + 1) |> loop_1(args)
    else
      ctx
    end
  end
