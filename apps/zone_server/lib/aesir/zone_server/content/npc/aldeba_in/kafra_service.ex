          ctx =
            if v2 == 1 do
              ctx =
                if count_item(ctx, 1084) == 0 do
                  ctx
                  |> mes("[Kafra Pavianne]")
                  |> mes("I'm sorry, but you don't have any Kafra Passes.")
                  |> close()
                  |> cutin("", 255)

                  exit(:normal)
                else
                  ctx
                end

              ctx = delitem(ctx, 1084, count_item(ctx, 1084))

              ctx
              |> credit_zeny(get_local(ctx, :kafrapassmoney, 0))
