            if count_item(ctx, 1084) == 1 do
              ctx
              |> mes("You have 1 Kafra Pass.")
              |> mes(
                "You can sell that pass to us for 2000 zeny. Would you like to sell this Kafra Pass back to the Kafra Corporation?"
              )
            else
