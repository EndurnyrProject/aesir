      if v1 == 1 do
        if count_item(ctx, 1084) == 0 do
          ctx
          |> mes("[Kafra Pavianne]")
          |> mes("I'm sorry,")
          |> mes("but you don't")
          |> mes("have any Kafra Passes.")
          |> close()
          |> cutin("", 255)

          exit(:normal)
