    {ctx, _} = s_l_mission(ctx, [])
    ctx
  catch
    :throw, {:script_end, ctx} -> ctx
  end

  defp s_l_mission(ctx, args) do
    try do
      ctx = mes(ctx, "Mmm?")

      ctx =
        ctx
        |> mes(Rathena.concat(Rathena.concat("Swordman ", char_name(ctx, 0)), "."))
        |> mes("How are the tests?")

      if Rathena.truthy?(Enum.at(args, 0, 0)) do
        ctx =
          ctx
          |> mes("Ah~ You do not know")
          |> mes("who to visit next?")
          |> next()
          |> mes("[Captain Herman]")

        throw({:script_return, {ctx, nil}})
      else
        ctx = ctx |> mes("It may be difficult,") |> mes("but do your best.") |> close()
        throw({:script_end, ctx})
      end
    catch
      :throw, {:script_return, result} -> result
    end
  end
