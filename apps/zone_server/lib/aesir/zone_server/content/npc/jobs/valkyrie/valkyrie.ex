defmodule Aesir.ZoneServer.Content.Npc.Jobs.Valkyrie.Valkyrie do
  @moduledoc """
  Transpiled from rAthena jobs/valkyrie.txt:43 (Valkyrie#).

  Regenerated by `mix aesir.import.npcs`; hand edits are detected through
  the transpile manifest and future imports land in `_conflicts/` instead
  of overwriting them.
  """

  use Aesir.ZoneServer.Npc,
    scope: :shared,
    spawn: [
      %{
        map: "valkyrie",
        x: 48,
        y: 86,
        dir: 4,
        sprite: 811,
        name: "Valkyrie",
        scope: :shared,
        unique_name: "Valkyrie#"
      }
    ]

  alias Aesir.ZoneServer.Script.Rathena

  @impl true
  def on_talk(ctx) do
    if get_char_var(ctx, :ADVJOB, 0) != 0 or get_char_var(ctx, :Upper, 0) == 1 do
      ctx =
        ctx
        |> mes("[Valkyrie]")
        |> mes("Welcome")
        |> mes("to Valhalla,")
        |> mes("the Hall of Honor.")
        |> next()
        |> mes("[Valkyrie]")
        |> mes("Please make")
        |> mes("yourself comfortable")
        |> mes("while you are here.")
        |> mes("Honor to the warriors!")
        |> close()

      throw({:script_end, ctx})
    else
      if base_level(ctx) > 98 and job_level(ctx) > 49 and class(ctx) >= :knight and
           class(ctx) <= :crusader2 do
        ctx =
          ctx
          |> mes("[Valkyrie]")
          |> mes("Welcome")
          |> mes("to Valhalla,")
          |> mes("the Hall of Honor.")
          |> next()
          |> mes("[Valkyrie]")
          |> mes("You will now end")
          |> mes("your present life and")
          |> mes("begin an entirely new life.")
          |> mes("Honor to the warriors!")
          |> next()

        if weight(ctx) > 0 or zeny(ctx) > 0 or checkcart(ctx) != 0 or checkfalcon(ctx) != 0 or
             ismounting(ctx) != 0 do
          ctx =
            ctx
            |> mes("[Valkyrie]")
            |> mes("There are a few things you must")
            |> mes("do before we start. You must")
            |> mes("first empty your mind and body.")
            |> mes("Honor comes when you abandon")
            |> mes("all your selfish desires...")
            |> next()
            |> mes("[Valkyrie]")
            |> mes(
              "You cannot take anything with you to the next life. Your items, zeny, pets and Pushcart all have to be left behind."
            )
            |> next()
            |> mes("[Valkyrie]")
            |> mes("When you are ready")
            |> mes("please return to me,")
            |> mes("brave adventurer.")
            |> close()
            |> warp("yuno_in02", 93, 205)

          throw({:script_end, ctx})
        else
          ctx =
            ctx
            |> mes("[Valkyrie]")
            |> mes("I see you've already")
            |> mes("released yourself from")
            |> mes("all worldy attachments,")

          ctx =
            ctx
            |> mes(Rathena.concat(Rathena.concat("", char_name(ctx, 0)), "."))
            |> next()
            |> mes("[Valkyrie]")
            |> mes(
              "That's an admirable attitude for an adventurer such as yourself. Honor comes when you abandon all personal desires for the sake of mankind."
            )
            |> next()

          ctx =
            if Rathena.truthy?(get_char_var(ctx, :SkillPoint, 0)) do
              ctx =
                ctx
                |> mes("[Valkyrie]")
                |> mes("Hmm... I sense that you have")
                |> mes("some lingering attachment or")
                |> mes("unfinished business in your")
                |> mes("current life. Take care of that,")
                |> mes("and bring closure to your present life.")
                |> close()
                |> warp("yuno_in02", 93, 205)

              throw({:script_end, ctx})
            else
              ctx
            end

          {ctx, _} =
            ctx
            |> mes("[Valkyrie]")
            |> mes("Now, let me remove all")
            |> mes("of your present memories...")
            |> mes("However, you will be able to")
            |> mes("remember the most honorable")
            |> mes("moments of this life.")
            |> next()
            |> mes("[Valkyrie]")
            |> mes("With one,")
            |> mes("I will ask the")
            |> mes("goddess Urd to remove")
            |> mes("all of your present")
            |> mes("memories.")
            |> next()
            |> mes("[Valkyrie]")
            |> mes("With two,")
            |> mes("I will ask the")
            |> mes("goddess Verdandi to keep")
            |> mes("and record the most honorable moments of your present life.")
            |> next()
            |> mes("[Valkyrie]")
            |> mes("With three,")
            |> mes("I will ask the")
            |> mes("goddess Skuld to")
            |> mes("guide you to your")
            |> mes("next life.")
            |> next()
            |> mes("[Valkyrie]")
            |> mes("One...")
            |> Aesir.ZoneServer.Content.Npc.Functions.FClearjobvar.call([])

          ctx =
            ctx
            |> next()
            |> mes("[Valkyrie]")
            |> mes("One...")
            |> mes("Two......")
            |> next()
            |> mes("[Valkyrie]")
            |> mes("One...")
            |> mes("Two......")
            |> mes("And Three.")

          ctx =
            set_char_var(ctx, :ADVJOB, Rathena.job_id(class(ctx)) + Rathena.job_id(:novice_high))

          ctx =
            if get_char_var(ctx, :ADVJOB, 0) == :lord_knight2 do
              set_char_var(ctx, :ADVJOB, :lord_knight)
            else
              ctx
            end

          ctx =
            if get_char_var(ctx, :ADVJOB, 0) == :paladin2 do
              set_char_var(ctx, :ADVJOB, :paladin)
            else
              ctx
            end

          ctx = ctx |> jobchange(:novice_high) |> resetlvl(1)

          ctx =
            ctx
            |> set_char_var(
              :MISC_QUEST,
              :erlang.band(get_char_var(ctx, :MISC_QUEST, 0), :erlang.bnot(1024))
            )
            |> skill(142, 1, :permanent)
            |> skill(143, 1, :permanent)
            |> completequest(1000)
            |> next()
            |> mes("[Valkyrie]")
            |> mes("Congratulations.")
            |> mes("You are now reborn")
            |> mes("into a brand new life.")
            |> mes("Please take these small gifts")
            |> mes("in preparation for your new adventures.")
            |> give_item(1202, 1)
            |> give_item(2302, 1)
            |> next()
            |> mes("[Valkyrie]")
            |> mes(
              "I wish that the release the goddess Urd has granted you proves to be a blessing. I hope that the memories Verdandi has recorded will always honor you."
            )
            |> next()
            |> mes("[Valkyrie]")
            |> mes(
              "And I pray that the new life to which the goddess Skuld will guide you will be even more honorable than your last."
            )
            |> close()

          v1 = get_char_var(ctx, :ADVJOB, 0)

          ctx =
            case v1 do
              v when v in [4008, 4015] ->
                ctx =
                  if Rathena.truthy?(checkre(ctx, 0)) do
                    warp(ctx, "izlude", 129, 97)
                  else
                    warp(ctx, "izlude", 94, 103)
                  end

                ctx

              v when v in [4009, 4016] ->
                warp(ctx, "prontera", 273, 354)

              v when v in [4010, 4017] ->
                warp(ctx, "geffen", 120, 60)

              v when v in [4011, 4019] ->
                warp(ctx, "alberta", 116, 57)

              v when v in [4012, 4020, 4021] ->
                warp(ctx, "payon", 69, 100)

              v when v in [4013, 4018] ->
                warp(ctx, "morocc", 154, 50)

              _ ->
                warp(ctx, "yuno_in02", 93, 205)
            end

          throw({:script_end, ctx})
        end
      else
        ctx =
          ctx
          |> mes("[Valkyrie]")
          |> mes("Welcome")
          |> mes("to Valhalla,")
          |> mes("the Hall of Honor.")
          |> next()
          |> mes("[Valkyrie]")
          |> mes(
            "Unfortunately, you have not yet been invited here. I ask you to leave immediately. Honor to the warriors!"
          )
          |> close()
          |> warp("yuno_in02", 93, 205)

        throw({:script_end, ctx})
      end
    end
  catch
    :throw, {:script_end, ctx} -> ctx
  end
end
