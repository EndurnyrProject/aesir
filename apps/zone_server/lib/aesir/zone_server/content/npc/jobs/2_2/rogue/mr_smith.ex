      |> mes("application fee:")
      |> mes("^FF000010,000 zeny^000000.")
      |> next()
      |> mes("[Mr. Smith]")
      |> mes("We also need")
      |> mes("you to bring")
      |> mes(Rathena.concat(Rathena.concat("^FF0000", Enum.at(args, 0, 0)), "^000000,"))
      |> mes(Rathena.concat(Rathena.concat("^FF0000", Enum.at(args, 1, 0)), "^000000,"))
      |> mes(Rathena.concat(Rathena.concat("^FF0000", Enum.at(args, 2, 0)), "^000000 and"))
      |> mes(Rathena.concat(Rathena.concat("^FF0000", Enum.at(args, 3, 0)), "^000000."))
      |> set_local(:var, Enum.at(args, 4, 0))

    ctx = set_char_var(ctx, :ROGUE_Q, get_local(ctx, :var, 0))

    ctx =
      if get_local(ctx, :var, 0) == 3 do
        changequest(ctx, 2017, 2018)
      else
        ctx =
          if get_local(ctx, :var, 0) == 4 do
            changequest(ctx, 2017, 2019)
          else
            changequest(ctx, 2017, 2020)
          end

        ctx
      end

    ctx =
      ctx
      |> next()
      |> mes("[Mr. Smith]")
      |> mes("Hmm...?")
      |> mes("What was that?")
      |> mes("Did you just say that")
      |> mes("you're willing to donate")
