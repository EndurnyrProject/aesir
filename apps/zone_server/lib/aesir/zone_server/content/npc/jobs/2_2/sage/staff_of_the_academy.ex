  defp loop_5(ctx) do
    if get_local(ctx, :i, 0) < get_local(ctx, :size, 0) and
         count_item(ctx, Enum.at(get_local(ctx, :item, []), get_local(ctx, :i, 0), 0)) >=
           Enum.at(get_local(ctx, :count, []), get_local(ctx, :i, 0), 0) do
      ctx |> set_local(:i, get_local(ctx, :i, 0) + 1) |> loop_5()
    else
      ctx
    end
  end

