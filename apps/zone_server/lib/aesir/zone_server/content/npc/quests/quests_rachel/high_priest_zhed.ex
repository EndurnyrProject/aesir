  defp after_temple(ctx) do
    volcano = get_char_var(ctx, :aru_vol, 0)

    cond do
      get_char_var(ctx, :rachel_camel, 0) != 25 -> resting(ctx)
      get_char_var(ctx, :aru_monas, 0) == 11 -> veins_incident(ctx)
      volcano == 0 -> volcano_building(ctx)
      volcano in 1..4 -> camp_topics(ctx)
      volcano == 5 -> ctx |> cutin("ra_gman", 2) |> geological_report() |> farewell()
      volcano in 6..25 -> geologist_reminder(ctx)
      volcano == 26 -> camp_evacuated(ctx)
      volcano > 26 -> peace_to_arunafeltz(ctx)
      true -> headache(ctx)
    end
  end

