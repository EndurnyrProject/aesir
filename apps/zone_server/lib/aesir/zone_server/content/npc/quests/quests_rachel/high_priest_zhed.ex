defmodule Aesir.ZoneServer.Content.Npc.Quests.QuestsRachel.HighPriestZhed do
  @moduledoc """
  A moderate Rachel high priest who drives the Lost Boy, temple, Thor Volcano camp and
  Peace to Arunafeltz storylines.

  ## Behavior

  - Turns away players who cannot carry 200 more Glacial Hearts.
  - Receives Vincent's package and rewards the courier with experience.
  - Asks the courier to secretly tell the pope about the outside world, hands out the
    recommendation, then warns about the Holy Ground and rewards the player after the visit.
  - Explains the Veins smuggling incident to Nameless Island seekers and sends them to Niren.
  - Guides the Thor Volcano camp infiltration, from the geological report to the evacuation
    reward.
  - Enlists the player to win Niren and the pope over to peace, then rewards the outcome.

  ## Credits

  - Original from rAthena, authors and Contributors
    - L0ne_W0lf
    - Euphy

  ## Adaptation

  - Transpiled by mix aesir.import.npcs from rAthena script
  - LLM-assisted Elixir refactor reviewed by Cλstor
