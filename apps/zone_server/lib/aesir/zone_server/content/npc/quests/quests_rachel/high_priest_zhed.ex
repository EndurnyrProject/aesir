  use Aesir.ZoneServer.Npc,
    scope: :shared,
    spawn: [
      %{
        map: "ra_temin",
        x: 277,
        y: 159,
        dir: 3,
        sprite: 932,
        name: "High Priest Zhed",
        scope: :shared,
        unique_name: "High Priest Zhed#rachel"
      }
    ]

  alias Aesir.ZoneServer.Script.Rathena

  @impl true
  def on_talk(ctx) do
    ctx = skip_lost_boy_after_temple(ctx)

    if checkweight(ctx, [{908, 200}]) == 0 do
      overweight(ctx)
    else
      talk(ctx)
    end
  catch
    :throw, {:script_end, ctx} -> ctx
  end

  defp skip_lost_boy_after_temple(ctx) do
    if get_char_var(ctx, :ra_tem_q, 0) > 14 or temple_quest_done?(ctx) do
      set_char_var(ctx, :lost_boy, 14)
    else
      ctx
    end
  end

  defp temple_quest_done?(ctx), do: :erlang.band(get_char_var(ctx, :MISC_QUEST, 0), 8192) != 0

  defp overweight(ctx) do
    ctx
    |> mes("^3355FFWait a second!")
    |> mes("Right now, you're carrying")
    |> mes("too many things with you.")
    |> mes("Please come back after")
    |> mes("using the Kafra Service")
    |> mes("to store some of your items.^000000")
    |> close()
  end

  defp talk(ctx) do
    lost_boy = get_char_var(ctx, :lost_boy, 0)
    temple = get_char_var(ctx, :ra_tem_q, 0)

    cond do
      lost_boy == 12 -> receive_package(ctx)
      lost_boy == 13 and temple < 14 -> package_thanks(ctx)
      lost_boy == 13 and temple == 14 -> secret_favor(ctx)
      temple in [15, 16] -> recommendation_reminder(ctx)
      temple == 17 -> holy_ground_slip(ctx)
      temple == 18 -> still_discussing(ctx)
      temple == 19 -> ask_about_bekento(ctx)
      temple in 20..21 -> stay_away_from_holy_ground(ctx)
      temple == 23 -> suspended(ctx)
      temple_quest_done?(ctx) -> after_temple(ctx)
      true -> ctx |> cutin("ra_gman", 2) |> zhed() |> mes("May Freya be with you.") |> farewell()
    end
  end

  defp zhed(ctx), do: mes(ctx, "[High Priest Zhed]")

  defp player(ctx), do: mes(ctx, "[#{char_name(ctx, 0)}]")

  defp farewell(ctx), do: ctx |> close2() |> cutin("", 255)

  defp exp_by_mode(ctx, renewal, pre_renewal) do
    if Rathena.truthy?(checkre(ctx, 3)), do: renewal, else: pre_renewal
  end

