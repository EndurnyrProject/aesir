        |> mes("I better hurry and bring")
        |> mes("him medicine from Siria")
        |> mes("in Hugel as soon as I can!")
        |> close()

      v when v in [3, 4, 5] ->
        ctx
        |> mes("[#{char_name(ctx, 0)}]")
        |> mes("Oh no... Morriphen")
        |> mes("doesn't look good at all!")
        |> mes("I better hurry and bring")
