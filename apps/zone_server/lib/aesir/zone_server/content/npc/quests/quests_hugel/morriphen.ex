        ctx
        |> mes("[#{char_name(ctx, 0)}]")
        |> mes("What am I doing...?")
        |> mes("I need to return to")
        |> mes("Hugel and deliver this")
        |> mes("medicine to Siria as")
        |> mes("soon as possible!")
        |> close()

      8 ->
        hear_story(ctx)

      _ ->
        ctx
