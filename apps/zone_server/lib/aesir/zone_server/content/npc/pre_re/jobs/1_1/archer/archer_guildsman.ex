  the transpile manifest and future imports land in `_conflicts/` instead
  of overwriting them.
  """

  use Aesir.ZoneServer.Npc,
    scope: :pre_renewal,
    spawn: [
      %{
        map: "payon_in02",
        x: 64,
        y: 71,
        dir: 4,
        sprite: 85,
        name: "Archer Guildsman",
        scope: :pre_renewal,
        unique_name: "Archer Guildsman#archer"
      }
    ]

  alias Aesir.ZoneServer.Script.Rathena

  @impl true
  def on_talk(ctx) do
    ctx =
      if get_char_var(ctx, :Upper, 0) == 1 do
        if class(ctx) == :novice_high and
             (get_char_var(ctx, :ADVJOB, 0) == :sniper or get_char_var(ctx, :ADVJOB, 0) == :clown or
                get_char_var(ctx, :ADVJOB, 0) == :gypsy) do
          ctx =
            ctx
            |> mes("[Archer Guildsman]")
            |> mes("Hey, I know you.")
            |> mes("You took this test")
            |> mes("before, didn't you?")
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes("Ah, you must have been")
            |> mes("to Valhalla and been reborn.")
            |> mes("Wow, that's so impressive!")
            |> next()

          v1 = can_change_job?(ctx)

          ctx =
            if not Rathena.truthy?(v1) do
              ctx =
                ctx
                |> mes("[Archer Guildsman]")
                |> mes("Err...")
                |> mes(
                  "You'd better learn all the Basic Skills first before you can become an Archer."
                )
                |> next()
                |> mes("[Archer Guildsman]")
                |> mes("Alright, see you later.")
                |> close()

              throw({:script_end, ctx})
            else
              ctx
            end

          ctx =
            ctx
            |> mes("[Archer Guildsman]")
            |> mes("Well then. I don't")
            |> mes("need to say anything else.")
            |> mes("I know you'll make a great Archer...")
            |> next()
            |> skill(143, 0, :permanent)
            |> jobchange(:archer_high)
            |> skill(147, 1, :permanent)
            |> skill(148, 1, :permanent)
            |> mes("[Archer Guildsman]")
            |> mes("Although there's no special")
            |> mes("reward for you this time, I hope you understand. Take care of yourself.")
            |> close()

          throw({:script_end, ctx})
        else
          ctx =
            ctx
            |> mes("[Archer Guildsman]")
            |> mes("Oh...?")
            |> mes("Hey, what are")
            |> mes("you doing here...?")
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes(
              "I can tell that you're not cut out to be an Archer. It sort of feels like you're meant to do"
            )
            |> mes("something else...")
            |> close()

          throw({:script_end, ctx})
        end
      else
        ctx
      end

    {ctx, v2} =
      ctx
      |> mes("[Archer Guildsman]")
      |> mes("Good day. How may I help you?")
      |> next()
      |> select([
        "I want to be an Archer.",
        "I need the requirements, please.",
        "Nothing, thanks."
      ])

    ctx =
      case v2 do
        1 ->
          ctx =
            if base_job(ctx) == :archer do
              ctx =
                ctx
                |> mes("[Archer Guildsman]")
                |> mes("You've already become an Archer...")
                |> close()

              throw({:script_end, ctx})
            else
              ctx =
                if base_job(ctx) != :archer and base_job(ctx) != :novice do
                  ctx =
                    ctx
                    |> mes("[Archer Guildsman]")
                    |> mes("Hmm...")
                    |> mes("You don't look much like a Novice at all...")
                    |> next()
                    |> mes("[Archer Guildsman]")
                    |> mes(
                      "Anyway, whatever you are, you can't choose a job as an Archer because you have a job already."
                    )
                    |> close()

                  throw({:script_end, ctx})
                else
                  ctx
                end

              ctx
            end

          ctx =
            if get_char_var(ctx, :job_archer_q, 0) == 0 do
              {ctx, v3} =
                ctx
                |> mes("[Archer Guildsman]")
                |> mes("Do you want to be an Archer?")
                |> mes("If so, you need to fill out this application form.")
                |> next()
                |> select(["Apply.", "Cancel"])

              ctx =
                if v3 == 1 do
                  {ctx, v4} =
                    ctx
                    |> set_char_var(:job_archer_q, 1)
                    |> setquest(1004)
                    |> mes("[Archer Guildsman]")
                    |> mes(
                      "Okay, sign here. Alright, um, I'll promote you once you meet the requirements."
                    )
                    |> next()
                    |> mes("[Archer Guildsman]")
                    |> mes("If you think you've met them already, we can check that now.")
                    |> mes("Are you ready?")
                    |> next()
                    |> select(["Yes, I am.", "No, not yet."])

                  ctx =
                    if v4 == 1 do
                      ctx |> mes("[Archer Guildsman]") |> mes("Alright, let me check.") |> next()
                    else
                      ctx =
                        ctx
                        |> mes("[Archer Guildsman]")
                        |> mes(
                          "I understand. Be my guest if you want to look at the requirements."
                        )
                        |> close()

                      throw({:script_end, ctx})
                    end

                  ctx
                else
                  ctx =
                    ctx
                    |> mes("[Archer Guildsman]")
                    |> mes("Well, alright.")
                    |> mes("See you next time.")
                    |> close()

                  throw({:script_end, ctx})
                end

              ctx
            else
              ctx
            end

          ctx = mes(ctx, "[Archer Guildsman]")

          ctx =
            ctx
            |> mes(Rathena.concat(Rathena.concat("Are you...", char_name(ctx, 0)), "?"))
            |> next()

          v5 = can_change_job?(ctx)

          ctx =
            if not Rathena.truthy?(v5) do
              ctx =
                ctx
                |> mes("[Archer Guildsman]")
                |> mes(
                  "Well, you're not at the right job level. Please check the requirements again."
                )
                |> next()
                |> mes("[Archer Guildsman]")
                |> mes(
                  "Your job level must be at least 10, and don't forget you should learn all of the Basic Skills. Once you've done that, come back."
                )
                |> close()

              throw({:script_end, ctx})
            else
              ctx
            end

          ctx =
            if get_char_var(ctx, :job_archer_q, 0) == 1 do
              ctx = set_local(ctx, :archer_item1, count_item(ctx, 1066) * 5)
              ctx = set_local(ctx, :archer_item2, count_item(ctx, 1067) * 3)
              ctx = set_local(ctx, :archer_item3, count_item(ctx, 1068) * 2)
              ctx = set_local(ctx, :archer_item4, count_item(ctx, 1019))

              ctx =
                set_local(
                  ctx,
                  :total_archer,
                  get_local(ctx, :archer_item1, 0) + get_local(ctx, :archer_item2, 0) +
                    get_local(ctx, :archer_item3, 0) + get_local(ctx, :archer_item4, 0)
                )

              ctx =
                ctx
                |> set_local(
                  :total_archer2,
                  (get_local(ctx, :archer_item2, 0) + get_local(ctx, :archer_item3, 0)) * 2 +
                    get_local(ctx, :archer_item4, 0)
                )
                |> mes("[Archer Guildsman]")
                |> mes("Excellent!")
                |> mes("Now then,")
                |> mes("let's see...")
                |> next()
                |> mes("[Archer Guildsman]")
                |> mes(
                  "I will appraise the value of the various types of Trunks, needed to produce a Bow, that you've brought."
                )
                |> next()

              ctx =
                if count_item(ctx, 1066) == 0 and count_item(ctx, 1067) == 0 and
                     count_item(ctx, 1068) == 0 and count_item(ctx, 1019) == 0 do
                  ctx =
                    ctx
                    |> mes("[Archer Guildsman]")
                    |> mes("Um...")
                    |> mes(
                      "Unfortunately you didn't bring any of the required items. There's nothing for me to appraise."
                    )
                    |> close()

                  throw({:script_end, ctx})
                else
                  ctx
                end

              ctx = mes(ctx, "[Archer Guildsman]")

              ctx =
                if count_item(ctx, 1066) != 0 do
                  mes(
                    ctx,
                    Rathena.concat(
                      Rathena.concat(
                        Rathena.concat(
                          Rathena.concat(" Grade S : ", count_item(ctx, 1066)),
                          " ea, Grade: "
                        ),
                        get_local(ctx, :archer_item1, 0)
                      ),
                      " . "
                    )
                  )
                else
                  ctx
                end

              ctx =
                if count_item(ctx, 1067) != 0 do
                  mes(
                    ctx,
                    Rathena.concat(
                      Rathena.concat(
                        Rathena.concat(
                          Rathena.concat(" Grade A : ", count_item(ctx, 1067)),
                          " ea, Grade : "
                        ),
                        get_local(ctx, :archer_item2, 0)
                      ),
                      " . "
                    )
                  )
                else
                  ctx
                end

              ctx =
                if count_item(ctx, 1068) != 0 do
                  mes(
                    ctx,
                    Rathena.concat(
                      Rathena.concat(
                        Rathena.concat(
                          Rathena.concat(" Grade B : ", count_item(ctx, 1068)),
                          " ea, Grade : "
                        ),
                        get_local(ctx, :archer_item3, 0)
                      ),
                      " . "
                    )
                  )
                else
                  ctx
                end

              ctx =
                if count_item(ctx, 1019) != 0 do
                  mes(
                    ctx,
                    Rathena.concat(
                      Rathena.concat(
                        Rathena.concat(
                          Rathena.concat(" Grade C : ", count_item(ctx, 1019)),
                          " ea, Grade : "
                        ),
                        get_local(ctx, :archer_item4, 0)
                      ),
                      " . "
                    )
                  )
                else
                  ctx
                end

              ctx =
                if get_local(ctx, :total_archer, 0) < 25 do
                  ctx =
                    ctx
                    |> mes(
                      Rathena.concat(
                        Rathena.concat("Total Grades: ^FF0000", get_local(ctx, :total_archer, 0)),
                        "^000000 / 40"
                      )
                    )
                    |> next()
                    |> mes("[Archer Guildsman]")
                    |> mes(
                      "Less than 25!? You have to get a grade of at least 25! Come on, try harder!"
                    )
                    |> close()

                  throw({:script_end, ctx})
                else
                  ctx =
                    ctx
                    |> mes(
                      Rathena.concat(
                        Rathena.concat("Total Grades: ^0000FF", get_local(ctx, :total_archer, 0)),
                        "^000000 / 40"
                      )
                    )
                    |> next()
                    |> mes("[Archer Guildsman]")

                  ctx =
                    if get_local(ctx, :total_archer, 0) > 40 do
                      ctx |> mes("Wow! More than 40!") |> mes("Excellent! Congratulations!")
                    else
                      ctx =
                        if get_local(ctx, :total_archer, 0) > 30 do
                          ctx |> mes("More than 30! Nice job!") |> mes("Congratulations!")
                        else
                          mes(ctx, "*Sigh* Well, you just barely passed... Anyway, well done.")
                        end

                      ctx
                    end

                  ctx
                end

              ctx =
                ctx
                |> next()
                |> mes("[Archer Guildsman]")
                |> mes(
                  "I'll transfer these Trunks to our Bow Production Department. Now that you've met the requirements, let me promote you right away!"
                )

              ctx =
                if count_item(ctx, 1066) != 0 do
                  delitem(ctx, 1066, count_item(ctx, 1066))
                else
                  ctx
                end

              ctx =
                if count_item(ctx, 1067) != 0 do
                  delitem(ctx, 1067, count_item(ctx, 1067))
                else
                  ctx
                end

              ctx =
                if count_item(ctx, 1068) != 0 do
                  delitem(ctx, 1068, count_item(ctx, 1068))
                else
                  ctx
                end

              ctx =
                if count_item(ctx, 1019) != 0 do
                  delitem(ctx, 1019, count_item(ctx, 1019))
                else
                  ctx
                end

              ctx
            else
              ctx
            end

          {ctx, _} =
            ctx
            |> next()
            |> jobchange(:archer)
            |> Aesir.ZoneServer.Content.Npc.Functions.FClearjobvar.call([])

          ctx =
            ctx
            |> completequest(1004)
            |> mes("[Archer Guildsman]")
            |> mes("Congratulations!")
            |> mes("You are now an Archer!")
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes(
              "Of course, we expect that you will help contribute towards the future of the Archer Guild with your efforts."
            )
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes(
              "Ah, your bow has arrived from the Bow Production Department. Here, take it! It's yours~"
            )
            |> give_item(1702, 1)

          ctx =
            ctx
            |> give_item(1750, get_local(ctx, :total_archer2, 0))
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes(
              "Now, off you go. Hunt with pride, knowing you were trained by one of the best!"
            )
            |> close()

          throw({:script_end, ctx})

        2 ->
          ctx =
            ctx
            |> mes("[Archer Guildsman]")
            |> mes("I will explain the requirements for being an Archer.")

          ctx =
            if base_job(ctx) != :novice do
              ctx =
                if base_job(ctx) == :archer do
                  ctx
                  |> next()
                  |> mes("[Archer Guildsman]")
                  |> mes("But...")
                  |> mes("You're already an Archer. You should know these already...")
                else
                  ctx
                  |> next()
                  |> mes("[Archer Guildsman]")
                  |> mes(
                    "Wait a second. You've chosen a different job already. You don't need to know this~"
                  )
                end

              mes(ctx, "So...Yeah...no real reason to tell you the requirements...")
            else
              ctx
            end

          ctx =
            ctx
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes(
              "First of all, you have to the Job Level 9 as a Novice, and know all of the Basic Skills."
            )
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes(
              "An Archer needs extremely high concentration and reflexes, so we do not accept those who have little patience."
            )
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes(
              "You also have to gather ^FF0000Trunks^000000. There are 4 different types of Trunks, each of differing quality. You'll be given different grades for your Trunks, depending on their quality."
            )
            |> next()
            |> mes("[Archer Guildsman]")
            |> mes(
              "In order to become an Archer, you must receive a grade of at least ^0000FF25^000000 points out of 40. You can get Trunks from 'Willow,' the tree. Be careful, though. They can be tough monsters."
            )
            |> close()

          throw({:script_end, ctx})

        3 ->
          ctx = close(ctx)
          throw({:script_end, ctx})

        _ ->
          ctx
      end

    ctx
  catch
    :throw, {:script_end, ctx} -> ctx
  end
end
