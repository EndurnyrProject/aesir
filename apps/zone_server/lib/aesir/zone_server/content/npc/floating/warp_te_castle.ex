      set_local(ctx, :guild_id, Todo.call!(:getcastledata, [get_local(ctx, :"castle$", ""), 1]))

    ctx = set_local(ctx, :my_guild_id, getcharid(ctx, 2))

    ctx =
      if Rathena.truthy?(get_local(ctx, :guild_id, 0)) and
           get_local(ctx, :guild_id, 0) == get_local(ctx, :my_guild_id, 0) do
        ctx =
          todo(ctx, :warp, [
            get_local(ctx, :"castle$", ""),
            Enum.at(args, 1, 0),
            Enum.at(args, 2, 0)
          ])

        throw({:script_end, ctx})
      else
        ctx
      end

    ctx =
      if Todo.call!(:WoeTETimeStart, [3600]) == 1 do
        ctx =
          if not Rathena.truthy?(get_local(ctx, :guild_id, 0)) or
               not Rathena.truthy?(get_local(ctx, :my_guild_id, 0)) do
            ctx =
              ctx
              |> mes("It's time for preparing to WoE. Only Alliance guild is able to enter.")
              |> close()

            throw({:script_end, ctx})
          else
            ctx
          end

        ctx =
          if Todo.call!(:getguildalliance, [
               get_local(ctx, :my_guild_id, 0),
               get_local(ctx, :guild_id, 0)
             ]) != 1 do
            ctx =
              ctx
              |> mes("It's time for preparing to WoE. Only Alliance guild is able to enter.")
              |> close()

            throw({:script_end, ctx})
          else
            ctx
          end

        ctx |> mes("Welcome alliance guild.") |> close()
      else
        ctx
      end

    ctx =
      todo(ctx, :warp, [get_local(ctx, :"castle$", ""), Enum.at(args, 1, 0), Enum.at(args, 2, 0)])

