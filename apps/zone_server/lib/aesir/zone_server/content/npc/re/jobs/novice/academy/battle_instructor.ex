  defp loop_1(ctx) do
    if get_local(ctx, :i, 0) < 6 do
      result =
        try do
          ctx =
            ctx
            |> set_local(:quest_id, 11339 + get_local(ctx, :i, 0))
            |> set_local(:bexp, [90, 90, 135, 200, 0, 120])
            |> set_local(:jexp, [50, 50, 100, 175, 0, 90])
            |> set_local(:material, [909, 515, 914, 939, 0, 915])
            |> set_local(:count, [5, 1, 3, 3, 0, 2])

          ctx =
            if get_local(ctx, :quest_id, 0) == 11343 do
              throw({:cont_1, ctx})
            else
              ctx
            end

          ctx =
            if checkquest(ctx, get_local(ctx, :quest_id, 0), :hunting) == 1 do
              erasequest(ctx, get_local(ctx, :quest_id, 0))
            else
              ctx =
                if checkquest(ctx, get_local(ctx, :quest_id, 0), :hunting) == 2 do
                  ctx = erasequest(ctx, get_local(ctx, :quest_id, 0))

                  ctx =
                    if count_item(
                         ctx,
                         Enum.at(get_local(ctx, :material, []), get_local(ctx, :i, 0), 0)
                       ) >= Enum.at(get_local(ctx, :count, []), get_char_var(ctx, :i, 0), 0) do
                      ctx =
                        delitem(
                          ctx,
                          Enum.at(get_local(ctx, :material, []), get_local(ctx, :i, 0), 0),
                          Enum.at(get_local(ctx, :count, []), get_local(ctx, :i, 0), 0)
                        )

                      ctx
                      |> getexp(
                        Enum.at(get_local(ctx, :bexp, []), get_local(ctx, :i, 0), 0),
                        Enum.at(get_local(ctx, :jexp, []), get_local(ctx, :i, 0), 0)
                      )
                      |> give_item(7059, 1)
                    else
                      ctx
                    end

                  ctx
                else
                  ctx
                end

              ctx
            end

          {:next, ctx}
        catch
          :throw, {:brk_1, ctx} -> {:done, ctx}
          :throw, {:cont_1, ctx} -> {:next, ctx}
        end

      case result do
        {:next, ctx} ->
          ctx = set_local(ctx, :i, get_local(ctx, :i, 0) + 1)
          loop_1(ctx)

        {:done, ctx} ->
          ctx
      end
    else
      ctx
    end
  end
