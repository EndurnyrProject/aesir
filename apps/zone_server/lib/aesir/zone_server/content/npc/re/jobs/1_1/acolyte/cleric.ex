        y: 41,
        dir: 4,
        sprite: 60,
        name: "Cleric",
        unique_name: "Cleric#aco"
      }
    ]

  alias Aesir.ZoneServer.Script.Rathena

  @impl true
  def on_talk(ctx) do
    ctx =
      if get_char_var(ctx, :Upper, 0) == 1 do
        if get_char_var(ctx, :ADVJOB, 0) == :high_priest or
             get_char_var(ctx, :ADVJOB, 0) == :champion do
          if class(ctx) == :novice_high do
            ctx =
              ctx
              |> mes("[Father Mareusis]")
              |> mes("Ah, I sense you have endured")
              |> mes(
                "a past life experience. You must have learned many things before entering Valhalla."
              )
              |> next()

            v1 = can_change_job?(ctx)

            ctx =
              if not Rathena.truthy?(v1) do
                ctx =
                  ctx
                  |> mes("[Father Mareusis]")
                  |> mes(
                    "Unfortunately, I don't think you're ready to become an Acolyte yet. Please finish learning all of the Basic Skills first."
                  )
                  |> next()
                  |> mes("[Father Mareusis]")
                  |> mes("In the meantime,")
                  |> mes("I will wait until")
                  |> mes("you are ready.")
                  |> mes("May God be")
                  |> mes("with you.")
                  |> close()

                throw({:script_end, ctx})
              else
                ctx
              end

            ctx =
              ctx
              |> mes("[Father Mareusis]")
              |> mes("Well, I welcome you")
              |> mes("back from Valhalla and")
              |> mes("wish you luck on your")
              |> mes("new life's journey.")
              |> next()
              |> skill(143, 0, :permanent)
              |> jobchange(:acolyte_high)
              |> skill(156, 1, :permanent)
              |> mes("[Father Mareusis]")
              |> mes(
                "Now, venture forth and seek those who need your help. May God light your path."
              )
              |> close()

            throw({:script_end, ctx})
          else
            ctx =
              ctx
              |> mes("[Father Mareusis]")
              |> mes(
                "Now, venture forth to seek people who need your help. May God enlighten your way."
              )
              |> close()

            throw({:script_end, ctx})
          end
        else
          ctx =
            ctx
            |> mes("[Father Mareusis]")
            |> mes(
              "I sense that you have endured a past life experience. You must have learned many things before entering Valhalla."
            )
            |> next()
            |> mes("[Father Mareusis]")
            |> mes(
              "However, I can tell that you are not suited to be an Acolyte. Please remember who you were in your past life and find your path."
            )
            |> close()

          throw({:script_end, ctx})
        end
      else
        ctx
      end

    {ctx, v2} =
      ctx
      |> mes("[Father Mareusis]")
      |> mes("What is it that you seek?")
      |> next()
      |> select([
        "Change your job to acolyte.",
        "Ask the requirements to be an acolyte.",
        "Quit it."
      ])

    ctx =
      case v2 do
        1 ->
          ctx = mes(ctx, "[Father Mareusis]")

          if base_job(ctx) != :novice do
            ctx =
              if base_job(ctx) == :acolyte do
                mes(
                  ctx,
                  "Are you feeling okay today? I can tell by your attire that you are already an Acolyte. You're not joking around, are you?"
                )
              else
                mes(ctx, "I'm sorry but it seems you already have your own job, aren't you?")
              end

            ctx = close(ctx)
            throw({:script_end, ctx})
          else
            ctx =
              ctx
              |> mes("Do you truly wish to become a servant of God?")
              |> mes("Let's see whether you are ready for it or not... Hmm...")
              |> next()

            v3 = can_change_job?(ctx)

            ctx =
              if not Rathena.truthy?(v3) do
                ctx =
                  ctx
                  |> mes("[Father Mareusis]")
                  |> mes(
                    "Oh my?! You haven't accomplished the basic practice yet?! You have a long way to go! Come again after increasing your job level!"
                  )
                  |> close()

                throw({:script_end, ctx})
              else
                ctx
              end

            ctx =
              ctx
              |> mes("[Father Mareusis]")
              |> mes("Hmm... your job level is enough...")
              |> mes("Good. Now I will give you the qualification to become an Acolyte.")
              |> next()
              |> mes("[Father Mareusis]")
              |> mes(
                "Always remember to be thankful to God, who takes care of us all the time. In chaos and times of difficulty, face your hardships with unwavering faith."
              )
              |> jobchange(:acolyte)
              |> give_item(1545, 1)
              |> next()
              |> mes("[Father Mareusis]")
              |> mes(
                "Lastly, I want to sincerely congratulate you on persevering through your trial of penance."
              )
              |> close()

            throw({:script_end, ctx})
          end

        2 ->
          ctx =
            ctx
            |> mes("[Father Mareusis]")
            |> mes("Do you wish to become an Acolyte?")
            |> mes(
              "Then, you must fulfill the following requirements thinking those are the practices given by God."
            )
            |> next()
            |> mes("[Father Mareusis]")
            |> mes(
              "First, you have to reach at least Novice Job Level 9 and learn all of the Basic Skills."
            )
            |> mes(
              "This is the most basic thing to do, so you need to regard it as the way of training yourself."
            )
            |> next()
            |> mes("[Father Mareusis]")
            |> mes(
              "When you think you fulfilled this requirement, then come back to me again. Then you will have a holy job in which you can spread God's will."
            )
            |> close()

          throw({:script_end, ctx})

        3 ->
          ctx = close(ctx)
          throw({:script_end, ctx})

        _ ->
          ctx
      end

    ctx
  catch
    :throw, {:script_end, ctx} -> ctx
  end
