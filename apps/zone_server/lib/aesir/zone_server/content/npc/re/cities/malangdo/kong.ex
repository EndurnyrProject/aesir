                |> mes("We can't charge the hero of our fleet. What is your destination?")
                |> next()
              end

            ctx
          end

        ctx
      end

    {ctx, v1} =
      select(
        ctx,
        String.split(
          Rathena.concat(
            Rathena.concat(
              Rathena.concat(
                Rathena.concat("- Izlude destination --- ", get_local(ctx, :"s1$", "")),
                ":- Alberta destination --- "
              ),
              get_local(ctx, :"s1$", "")
            ),
            ":- Stay on Malangdo"
