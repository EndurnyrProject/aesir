      if zeny(ctx) < get_local(ctx, :price, 0) do
        ctx = ctx |> mes(get_local(ctx, :"no_money$", "")) |> close()
        throw({:script_end, ctx})
      else
        ctx
      end

    ctx = pay_zeny(ctx, get_local(ctx, :price, 0))
    ctx = mes(ctx, get_local(ctx, :"yes_money$", ""))

    ctx =
      if get_local(ctx, :i, 0) == 1 do
        warp(ctx, "izlude", 195, 212)
      else
        warp(ctx, "alberta", 192, 150)
      end

    close(ctx)
  catch
    :throw, {:script_end, ctx} -> ctx
  end
end
