      ctx
      |> mes("[Kong]")
      |> mes("Did you have fun in Malangdo?")
      |> mes("The fleet has a service to Izlude and Alberta.")
      |> next()

    ctx =
      if get_char_var(ctx, :ep13_yong1, 0) == 0 do
        ctx
        |> set_local(:price, 1000)
        |> set_local(:"s1$", "1000 zeny")
        |> set_local(:"s2$", "Have a nice day in Malangdo.")
        |> set_local(:"no_money$", "It is difficult for free.")
        |> set_local(:"yes_money$", "Have a nice trip.")
        |> mes("[Kong]")
        |> mes("The fee of ship is only 1000 zeny, where do you want to go?")
        |> next()
      else
        ctx =
          if get_char_var(ctx, :ep13_yong1, 0) < 60 do
            ctx
            |> set_local(:price, 999)
            |> set_local(:"s1$", "999 zeny")
            |> set_local(:"s2$", "Have a full of fortune day in Malangdo...")
            |> set_local(
              :"no_money$",
              "It is difficult even though you have a relationship with the fleet."
            )
            |> set_local(:"yes_money$", "Thanks, have a wonderful trip.")
            |> mes("[Kong]")
            |> mes(
              "You have a connection with our fleet. Apply special price 999 zeny. Where do you want to go?"
            )
            |> next()
          else
            ctx =
              if get_char_var(ctx, :ep13_yong1, 0) > 59 and get_char_var(ctx, :ep13_yong1, 0) < 80 do
                ctx
                |> set_local(:price, 500)
                |> set_local(:"s1$", "500 zeny")
                |> set_local(:"s2$", "There are full of fortune and jackpot in Malangdo.")
                |> set_local(
                  :"no_money$",
                  "Oh my god. You don't have 500 zeny? It is difficult for free."
                )
                |> set_local(:"yes_money$", "Have a nice trip and come again.")
                |> mes("[Kong]")
                |> mes(
                  "Wow~ You contributed to our fleet a lot. Alright!! Special discount price 500 zeny. Where do you want to go?"
                )
                |> next()
              else
                ctx
                |> set_local(:price, 0)
                |> set_local(:"s1$", "Free for the hero of our fleet!!")
                |> set_local(
                  :"s2$",
                  "No one objects to the hero of our fleet staying in Malangdo..."
                )
                |> mes("[Kong]")
                |> mes("Ah... You are the legendary hero of our cat's fleet.")
                |> next()
