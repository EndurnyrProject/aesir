    spawn: [
      %{map: "cmd_fild07", x: 299, y: 83, dir: 4, sprite: 100, name: "Zain"},
      %{map: "cmd_fild07", x: 94, y: 134, dir: 4, sprite: 100, name: "Sarumane"}
    ]

  alias Aesir.ZoneServer.Script.Rathena

  @impl true
  def on_talk(ctx) do
    ctx = set_local(ctx, :"n$", Rathena.concat(Rathena.concat("[", strnpcinfo(ctx, 1)), "]"))

    {ctx, v1} =
      ctx
      |> mes(get_local(ctx, :"n$", ""))
      |> mes("Would you like to")
      |> mes("board a ship on the")
      |> mes("Reudelus route? You")
      |> mes("can travel on Reudelus")
      |> mes("to Alberta or Izlude.")
      |> next()
      |> select(["Alberta - 600 Zeny", "Izlude - 800 Zeny", "Cancel"])

    ctx =
      try do
        case v1 do
          1 ->
            ctx =
              if zeny(ctx) < 600 do
                throw({:brk_1, ctx})
              else
                ctx
              end

            ctx |> pay_zeny(600) |> warp("alberta", 192, 169)
            exit(:normal)

          2 ->
            ctx =
              if zeny(ctx) < 800 do
                throw({:brk_1, ctx})
              else
                ctx
              end

            ctx = pay_zeny(ctx, 800)

            _ =
              if Rathena.truthy?(checkre(ctx, 0)) do
                warp(ctx, "izlude", 195, 212)
              else
                warp(ctx, "izlude", 176, 182)
              end

            exit(:normal)

          3 ->
            ctx
            |> mes(get_local(ctx, :"n$", ""))
            |> mes("Travel by ship is")
            |> mes("still one of the safest and")
            |> mes("dependable methods of")
            |> mes("transportation. I invite you")
            |> mes("to try Reudelus travel soon~")
            |> close()

            exit(:normal)

          _ ->
            ctx
        end
      catch
        :throw, {:brk_1, ctx} -> ctx
      end

    ctx
    |> mes(get_local(ctx, :"n$", ""))
    |> mes("I'm sorry, but you")
    |> mes("don't have enough")
    |> mes("zeny for the boarding fare.")
    |> close()

    exit(:normal)
  end
end
