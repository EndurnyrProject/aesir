      ctx
      |> mes("[Girl]")
      |> mes("If you like this")
      |> mes("area, why don't you")
      |> mes("stay and enjoy the")
      |> mes("the food and the sights!")
      |> next()

    ctx =
      if sex(ctx) == get_char_var(ctx, :SEX_MALE, 0) do
        ctx |> mes("[Girl]") |> mes("And by sights...") |> mes("I mean girls!") |> mes("Tee hee~")
      else
        ctx |> mes("[Girl]") |> mes("And the boys here") |> mes("aren't bad looking~")
      end

    close(ctx)
  catch
    :throw, {:script_end, ctx} -> ctx
  end
