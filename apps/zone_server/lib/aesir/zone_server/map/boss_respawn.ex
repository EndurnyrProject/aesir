defmodule Aesir.ZoneServer.Map.BossRespawn do
  @moduledoc """
  Durable shadow of a boss monster's in-memory respawn timer.

  `Coordinator` writes a row when a boss dies, alongside the live
  `Process.send_after` timer, and deletes it when the boss respawns. The
  timer is the sole live driver of the respawn; this table is never
  consulted while the server is running and exists only so a restart does
  not silently reset a camped boss's deadline (reconciled at boot).

  `write/3` never raises: a repo failure (validation or connection loss) is
  logged and swallowed, because losing durability for a single boss must not
  take down the coordinator or block the in-memory respawn that already
  drives the game.

  `reconcile/0` runs once at boot, before any coordinator starts. It issues a
  single grouped query for every pending row, matches them to spawn
  configuration greedily by `mob_id` within `map_name` (never positionally:
  spawn files are regenerated by an importer, so a positional key would rot on
  re-import), drops rows with no matching spawn slot, and caches the survivors
  per map for `deadlines_for/1`. It deliberately spawns nothing and arms no
  timer -- mob spawning is lazy, so anything spawned or armed at boot would be
  spawned a second time by the map's first `spawn_all_mobs`.
  """

  import Ecto.Query

  require Logger

  alias Aesir.Commons.Models.BossRespawn, as: Row
  alias Aesir.Repo
  alias Aesir.ZoneServer.Mmo.MobManagement

  @pending_key __MODULE__

  @typedoc "Pending respawn deadlines for one map, keyed by mob id, earliest first."
  @type deadlines :: %{integer() => [DateTime.t()]}

  @doc """
  Writes the pending deadline row for a boss that just died.
  """
  @spec write(String.t(), integer(), DateTime.t()) :: :ok
  def write(map_name, mob_id, respawn_at) do
    attrs = %{
      map_name: map_name,
      mob_id: mob_id,
      respawn_at: DateTime.truncate(respawn_at, :second)
    }

    %Row{}
    |> Row.changeset(attrs)
    |> Repo.insert()
    |> case do
      {:ok, _row} ->
        :ok

      {:error, changeset} ->
        Logger.error(
          "Failed to persist boss respawn for #{map_name}/#{mob_id}: #{inspect(changeset.errors)}"
        )

        :ok
    end
  rescue
    error ->
      Logger.error(
        "Boss respawn persistence unavailable for #{map_name}/#{mob_id}: #{Exception.message(error)}"
      )

      :ok
  end

  @doc """
  Deletes the pending deadline row(s) for a boss that just respawned.

  A no-op, not an error, when no row matches -- the caller does not need to
  know whether a row existed.
  """
  @spec delete(String.t(), integer()) :: :ok
  def delete(map_name, mob_id) do
    Repo.delete_all(pending_query(map_name, mob_id))
    :ok
  rescue
    error ->
      Logger.error(
        "Failed to delete boss respawn row for #{map_name}/#{mob_id}: #{Exception.message(error)}"
      )

      :ok
  end

  @doc """
  Lists every pending boss respawn row, for boot reconciliation.
  """
  @spec list_pending() :: [Row.t()]
  def list_pending do
    Repo.all(Row)
  end

  @doc """
  Loads every pending deadline into the boot cache, discarding orphan rows.

  A row is an orphan when the map's spawn configuration has no slot left for
  its mob id -- the boss no longer spawns there, or fewer of it spawn than
  there are pending rows. Orphans are logged and deleted rather than
  resurrecting a mob that should not exist.

  Nothing is spawned and no timer is armed; the deadlines are state that each
  map's first spawn consults.

  An unreachable repo is logged and degrades to no reconciliation: bosses then
  spawn normally on their maps' first visit and their timers restart from
  scratch. That matches the error handling of `write/3` and `delete/2` -- losing
  restart durability is acceptable, taking the zone server down with it is not.
  """
  @spec reconcile() :: :ok
  def reconcile do
    {by_map, orphans} =
      list_pending()
      |> Enum.group_by(& &1.map_name)
      |> Enum.reduce({%{}, []}, fn {map_name, rows}, {by_map, orphans} ->
        {matched, unmatched} = match_map_rows(map_name, rows)

        {Map.put(by_map, map_name, matched), unmatched ++ orphans}
      end)

    delete_orphans(orphans)
    :persistent_term.put(@pending_key, by_map)

    :ok
  rescue
    error ->
      Logger.error(
        "Boss respawn reconciliation unavailable, deadlines not restored: #{inspect(error)}"
      )

      :persistent_term.put(@pending_key, %{})

      :ok
  end

  @doc """
  Returns the reconciled deadlines for `map_name`, keyed by mob id.

  Empty when reconciliation has not run (no boot cache) or the map has no
  pending boss.
  """
  @spec deadlines_for(String.t()) :: deadlines()
  def deadlines_for(map_name) do
    @pending_key
    |> :persistent_term.get(%{})
    |> Map.get(map_name, %{})
  end

  @spec match_map_rows(String.t(), [Row.t()]) :: {deadlines(), [Row.t()]}
  defp match_map_rows(map_name, rows) do
    slots = spawn_slots(map_name)

    rows
    |> Enum.group_by(& &1.mob_id)
    |> Enum.reduce({%{}, []}, fn {mob_id, mob_rows}, {matched, orphans} ->
      {kept, dropped} =
        mob_rows
        |> Enum.sort_by(& &1.respawn_at, DateTime)
        |> Enum.split(Map.get(slots, mob_id, 0))

      {put_deadlines(matched, mob_id, kept), dropped ++ orphans}
    end)
  end

  @spec put_deadlines(deadlines(), integer(), [Row.t()]) :: deadlines()
  defp put_deadlines(matched, _mob_id, []), do: matched

  defp put_deadlines(matched, mob_id, rows),
    do: Map.put(matched, mob_id, Enum.map(rows, & &1.respawn_at))

  @spec spawn_slots(String.t()) :: %{integer() => pos_integer()}
  defp spawn_slots(map_name) do
    case MobManagement.get_spawns_for_map(map_name) do
      {:ok, spawns} ->
        Enum.reduce(spawns, %{}, fn spawn, acc ->
          Map.update(acc, spawn.mob, spawn.amount, &(&1 + spawn.amount))
        end)

      {:error, :no_spawns} ->
        %{}
    end
  end

  @spec delete_orphans([Row.t()]) :: :ok
  defp delete_orphans([]), do: :ok

  defp delete_orphans(orphans) do
    Enum.each(orphans, fn row ->
      Logger.warning(
        "Discarding orphan boss respawn row for #{row.map_name}/#{row.mob_id}: no matching spawn config"
      )
    end)

    ids = Enum.map(orphans, & &1.id)
    Repo.delete_all(from(r in Row, where: r.id in ^ids))

    :ok
  end

  defp pending_query(map_name, mob_id) do
    from(r in Row, where: r.map_name == ^map_name and r.mob_id == ^mob_id)
  end
end
