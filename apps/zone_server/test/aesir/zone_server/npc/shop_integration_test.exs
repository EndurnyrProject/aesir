defmodule Aesir.ZoneServer.Npc.ShopIntegrationTest do
  @moduledoc """
  End-to-end NPC shop coverage on the real stack against the **imported** corpus
  (`priv/db/shops/*.yml`, generated by `mix aesir.import.shops`). A live
  `PlayerSession` is driven entirely through the client-intent packets, with no
  hand-authored content and no stubbing of the shop subsystems:

    1. The player clicks a shop (`NpcTalk{shop_gid}`) and gets an `NpcShopOpen`
       carrying the shop's buy list and the player's sellable inventory, both
       priced server-side.
    2. The player buys an affordable item (`NpcBuyRequest`): the item is added
       and zeny debited atomically (in memory + persisted), and the client gets
       `ItemAdded` + a zeny `ParamChange` + `NpcBuyResult{ok}`.
    3. The player sells back an owned, sellable item (`NpcSellRequest`): the
       stack is reduced and zeny credited atomically, and the client gets
       `ItemRemoved` + a zeny `ParamChange` + `NpcSellResult{ok}`.

  The shop and the buy item are selected dynamically from the loaded `prontera`
  corpus (first affordable buy-priced item), so the test never hard-codes
  rAthena content that an importer re-run could change. The sell item is a real
  item-DB entry with a positive `sell` value (the corpus buy items ship none),
  so the sell path runs un-stubbed too.
  """

  use Aesir.ZoneServer.IntegrationCase

  @moduletag :capture_log

  alias Aesir.Commons.Models.Account
  alias Aesir.Commons.Models.Character
  alias Aesir.Commons.Models.InventoryItem
  alias Aesir.Commons.StatusParams
  alias Aesir.Net.ItemAdded
  alias Aesir.Net.ItemRemoved
  alias Aesir.Net.NpcBuyEntry
  alias Aesir.Net.NpcBuyRequest
  alias Aesir.Net.NpcBuyResult
  alias Aesir.Net.NpcSellEntry
  alias Aesir.Net.NpcSellRequest
  alias Aesir.Net.NpcSellResult
  alias Aesir.Net.NpcShopOpen
  alias Aesir.Net.NpcTalk
  alias Aesir.Net.ParamChange
  alias Aesir.Repo
  alias Aesir.ZoneServer.Mmo.ItemManagement
  alias Aesir.ZoneServer.Npc.Shop
  alias Aesir.ZoneServer.Npc.Shops
  alias Aesir.ZoneServer.Unit.Inventory.Persistence, as: InventoryPersistence
  alias Aesir.ZoneServer.Unit.Shop, as: ShopCore

  @map "prontera"
  @zeny_param StatusParams.zeny()
  @start_zeny 1_000_000
  @seed_amount 5
  @buy_amount 1
  @sell_amount 2

  setup do
    :ok = Shops.reload()
    buy = buy_pick()
    %{buy: buy, sell: sell_pick(buy.nameid)}
  end

  describe "open -> buy -> sell against the imported corpus" do
    test "drives the full loop through a live PlayerSession", %{buy: buy, sell: sell} do
      %{shop: shop, nameid: buy_nameid, price: buy_price} = buy
      sell_def = sell.item
      gid = Shop.Registry.entity_id(shop)

      character =
        insert_character("Shopper", zeny: @start_zeny, last_x: shop.x, last_y: shop.y)

      {:ok, _} =
        InventoryPersistence.insert_item(character.id, %{
          nameid: sell_def.id,
          amount: @seed_amount,
          identify: 1
        })

      session =
        start_player_session(character: character, map_name: @map, position: {shop.x, shop.y})

      on_exit(fn -> end_player_session(session) end)
      flush_packets()

      # 1. Click the shop -> the window opens with both server-priced lists.
      simulate_incoming_message(session.pid, %NpcTalk{npc_id: gid})

      assert_receive {:packet_sent,
                      %NpcShopOpen{unit_id: ^gid, buy_items: buy_items, sell_items: sell_items},
                      _},
                     1_000

      assert Enum.any?(buy_items, &(&1.nameid == buy_nameid and &1.price == buy_price))

      sell_entry = Enum.find(sell_items, &(&1.nameid == sell_def.id))
      assert sell_entry.amount == @seed_amount
      assert sell_entry.sell_price == sell_def.sell
      sell_index = sell_entry.inventory_index
      flush_packets()

      # 2. Buy the affordable item -> items+ / zeny- atomically.
      simulate_incoming_message(session.pid, %NpcBuyRequest{
        unit_id: gid,
        items: [%NpcBuyEntry{nameid: buy_nameid, amount: @buy_amount}]
      })

      assert_receive {:packet_sent, %ItemAdded{nameid: ^buy_nameid, amount: @buy_amount}, _},
                     1_000

      after_buy_zeny = @start_zeny - buy_price * @buy_amount

      assert_receive {:packet_sent, %ParamChange{var_id: @zeny_param, value: ^after_buy_zeny}, _},
                     1_000

      assert_receive {:packet_sent, %NpcBuyResult{result: 0}, _}, 1_000

      bought = get_player_state(session.pid)
      assert held(bought.inventory, buy_nameid) == @buy_amount
      assert bought.zeny == after_buy_zeny
      assert Repo.get(Character, character.id).zeny == after_buy_zeny
      persisted_after_buy = InventoryPersistence.load_inventory(character.id)

      assert Enum.any?(
               persisted_after_buy,
               &(&1.nameid == buy_nameid and &1.amount == @buy_amount)
             )

      flush_packets()

      # 3. Sell back the owned, sellable item -> items- / zeny+ atomically.
      simulate_incoming_message(session.pid, %NpcSellRequest{
        unit_id: gid,
        items: [%NpcSellEntry{inventory_index: sell_index, amount: @sell_amount}]
      })

      assert_receive {:packet_sent, %ItemRemoved{amount: @sell_amount}, _}, 1_000
      after_sell_zeny = after_buy_zeny + sell_def.sell * @sell_amount

      assert_receive {:packet_sent, %ParamChange{var_id: @zeny_param, value: ^after_sell_zeny},
                      _},
                     1_000

      assert_receive {:packet_sent, %NpcSellResult{result: 0}, _}, 1_000

      sold = get_player_state(session.pid)
      assert held(sold.inventory, sell_def.id) == @seed_amount - @sell_amount
      assert sold.zeny == after_sell_zeny
      assert Repo.get(Character, character.id).zeny == after_sell_zeny

      persisted_after_sell = InventoryPersistence.load_inventory(character.id)

      assert Enum.any?(
               persisted_after_sell,
               &(&1.nameid == sell_def.id and &1.amount == @seed_amount - @sell_amount)
             )
    end
  end

  # First loaded prontera shop with an item that resolves and carries a positive
  # effective buy price (override or `ItemDefinition.buy`).
  defp buy_pick do
    {:ok, shops} = Shops.for_map(@map)

    {shop, item} =
      Enum.find_value(shops, fn shop ->
        item =
          Enum.find(shop.items, fn it ->
            match?({:ok, _}, ItemManagement.get_item_by_id(it.nameid)) and
              ShopCore.effective_buy_price(shop, it.nameid) > 0
          end)

        item && {shop, item}
      end)

    %{shop: shop, nameid: item.nameid, price: ShopCore.effective_buy_price(shop, item.nameid)}
  end

  # Any real item-DB entry with a positive sell price, distinct from the buy item
  # (the corpus buy items ship no sell value, so a separate sellable item is seeded).
  defp sell_pick(exclude_nameid) do
    item =
      ItemManagement.get_all_items()
      |> Enum.find(&(&1.sell > 0 and &1.id != exclude_nameid))

    %{item: item}
  end

  defp insert_character(prefix, attrs) do
    uniq = System.unique_integer([:positive])

    {:ok, account} =
      %Account{}
      |> Account.changeset(%{
        username: "#{prefix}#{uniq}",
        userid: "#{prefix}#{uniq}",
        user_pass: "password",
        email: "#{prefix}#{uniq}@aesir.test"
      })
      |> Repo.insert()

    {:ok, character} =
      %Character{}
      |> Character.changeset(
        Map.merge(
          %{
            account_id: account.id,
            char_num: 0,
            name: "#{prefix}#{uniq}",
            class: 0,
            base_level: 50,
            job_level: 50,
            str: 10,
            agi: 10,
            vit: 10,
            int: 10,
            dex: 10,
            luk: 10,
            last_map: @map,
            last_x: 150,
            last_y: 150,
            save_map: @map,
            save_x: 150,
            save_y: 150
          },
          Map.new(attrs)
        )
      )
      |> Repo.insert()

    character
  end

  defp held(map, nameid) do
    Enum.reduce(map, 0, fn
      {_index, %InventoryItem{nameid: ^nameid, amount: amount}}, acc -> acc + amount
      _entry, acc -> acc
    end)
  end
end
