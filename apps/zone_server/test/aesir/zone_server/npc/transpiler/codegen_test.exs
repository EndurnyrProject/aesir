defmodule Aesir.ZoneServer.Npc.Transpiler.CodegenTest do
  use ExUnit.Case, async: true

  alias Aesir.ZoneServer.Npc.Transpiler.Codegen

  defp gen!(body, opts \\ []) do
    opts =
      Map.merge(
        %{
          module: "Aesir.ZoneServer.Content.Npc.Payon.TestNpc",
          kind: :script,
          source: "test.txt:1",
          spawns: [%{map: "payon", x: 1, y: 2, dir: 3, sprite: 58, name: "Test"}],
          functions: %{}
        },
        Map.new(opts)
      )

    {:ok, src} = Codegen.generate(body, opts)
    assert {:ok, _} = Code.string_to_quoted(src)
    src
  end

  test "simple dialog module snapshot" do
    src =
      gen!("""
      mes "Hello!";
      close;
      """)

    assert src == """
           defmodule Aesir.ZoneServer.Content.Npc.Payon.TestNpc do
             @moduledoc \"\"\"
             Transpiled from rAthena test.txt:1.

             Regenerated by `mix aesir.import.npcs`; hand edits are detected through
             the transpile manifest and future imports land in `_conflicts/` instead
             of overwriting them.
             \"\"\"

             use Aesir.ZoneServer.Npc, spawn: [%{map: "payon", x: 1, y: 2, dir: 3, sprite: 58, name: "Test"}]

             @impl true
             def on_talk(ctx) do
               ctx |> mes("Hello!") |> close()
               exit(:normal)
             end
           end
           """
  end

  test "consecutive ctx-threading calls collapse into a pipe chain" do
    src =
      gen!("""
      mes "a";
      mes "b";
      next;
      mes "c";
      close;
      """)

    assert src =~ ~S{ctx |> mes("a") |> mes("b") |> next() |> mes("c") |> close()}
  end

  test "a call reading ctx in its arguments opens a chain but never joins one" do
    src =
      gen!("""
      mes "a";
      mes strcharinfo(0);
      close;
      """)

    assert src =~ ~S{ctx = mes(ctx, "a")}
    assert src =~ ~S{ctx |> mes(to_string(char_name(ctx, 0))) |> close()}
  end

  test "branch bodies pipe; a lone rebind just drops the dead binding" do
    src =
      gen!("""
      if (BaseLevel > 10) {
        mes "big";
        next;
      }
      if (BaseLevel > 20) mes "huge";
      mes "done";
      close;
      """)

    assert src =~ ~S{ctx |> mes("big") |> next()}
    assert src =~ ~S{mes(ctx, "huge")}
    refute src =~ ~S{ctx = mes(ctx, "huge")}
    assert src =~ ~S{ctx |> mes("done") |> close()}
  end

  test "a trailing effect run before end loses the dead rebinding" do
    src =
      gen!("""
      close2;
      warp "prontera",155,180;
      end;
      """)

    assert src =~ ~S{ctx |> close() |> warp("prontera", 155, 180)}
    refute src =~ "ctx = ctx |> close()"
  end

  test "switch(select) with supported commands, char vars and zeny" do
    src =
      gen!("""
      mes "Want it?";
      next;
      switch (select("Yes:No")) {
      case 1:
        if (Zeny < 500) { mes "Too poor"; close; }
        Zeny -= 500;
        getitem 2278, 1;
        sphmask_q = 1;
        close;
      case 2:
        close;
      }
      """)

    assert src =~ "{ctx, v1} = ctx |> mes(\"Want it?\") |> next() |> select([\"Yes\", \"No\"])"
    assert src =~ "case v1 do"
    assert src =~ "if zeny(ctx) < 500 do"
    assert src =~ "|> pay_zeny(500)"
    assert src =~ "|> give_item(2278, 1)"
    assert src =~ "|> set_char_var(:sphmask_q, 1)"
    assert src =~ "_ ->"
  end

  test "unsupported buildins become todo stubs, expressions become Todo.call!" do
    src =
      gen!("""
      showscript "hi";
      if (getcharid(0) == 0) close;
      close;
      """)

    assert src =~ ~S|ctx = todo(ctx, :showscript, ["hi"])|
    assert src =~ "Todo.call!(:getcharid, [0]) == 0"
    assert src =~ "alias Aesir.ZoneServer.Script.Todo"
  end

  test "goto labels become never-returning functions with fall-through" do
    src =
      gen!("""
      mes "start";
      goto L_End;
      L_Mid:
      mes "mid";
      L_End:
      mes "bye";
      close;
      """)

    assert src =~ ~S{ctx |> mes("start") |> l_l_end()}
    assert src =~ "defp l_l_end(ctx) do"
    refute src =~ "defp l_l_mid"
  end

  test "label references resolve case-insensitively like rAthena" do
    src =
      gen!("""
      callsub S_Warpchar, 1;
      goto L_end;
      L_End:
      mes "bye";
      close;
      S_WarpChar:
      return;
      """)

    assert src =~ "{ctx, _} = s_s_warpchar(ctx, [1])"
    assert src =~ "defp s_s_warpchar"
    assert src =~ "l_l_end(ctx)"
    assert src =~ "defp l_l_end(ctx) do"
    refute src =~ "todo(ctx, :goto"
  end

  test "menu dispatches to label functions" do
    src =
      gen!("""
      menu "Buy",L_Buy,"Bye",L_Bye;
      L_Buy:
      close;
      L_Bye:
      close;
      """)

    assert src =~ ~S|{ctx, choice} = select(ctx, ["Buy", "Bye"])|
    assert src =~ "1 -> l_l_buy(ctx)"
    assert src =~ "2 -> l_l_bye(ctx)"
  end

  test "callsub returns {ctx, value} and getarg reads args" do
    src =
      gen!("""
      callsub S_Give, 5;
      close;
      S_Give:
      return getarg(0) + 1;
      """)

    assert src =~ "{ctx, _} = s_s_give(ctx, [5])"
    assert src =~ "defp s_s_give(ctx, args) do"
    assert src =~ "{ctx, Enum.at(args, 0, 0) + 1}"
  end

  test "while loop with plain body recurses; nested break uses throw" do
    plain =
      gen!("""
      while (.@i < 3) .@i++;
      close;
      """)

    assert plain =~ ~S{ctx |> loop_1() |> close()}
    assert plain =~ "defp loop_1(ctx) do"
    refute plain =~ "throw"

    thrown =
      gen!("""
      while (1) {
        if (.@i > 2) break;
        .@i++;
      }
      close;
      """)

    assert thrown =~ "throw({:brk_1, ctx})"
    assert thrown =~ ":throw, {:brk_1, ctx} -> {:done, ctx}"
  end

  test "for loop runs init before and step on iteration" do
    src =
      gen!("""
      for (.@i = 0; .@i < 10; .@i++) mes "x";
      close;
      """)

    assert src =~ "|> set_local(:i, 0)"
    assert src =~ "get_local(ctx, :i, 0) + 1"
  end

  test "local and session vars, arrays, dialog input" do
    src =
      gen!("""
      input .@name$;
      @step = 2;
      setarray .@list[0], 1, 2, 3;
      mes .@list[1] + "x" + @step;
      close;
      """)

    assert src =~ "{ctx, v1} = input(ctx, :string)"
    assert src =~ ~S{|> set_local(:"name$", v1)}
    assert src =~ "|> set_temp_var(:step, 2)"
    assert src =~ "|> set_local(:list, [1, 2, 3])"
    assert src =~ "Enum.at(get_local(ctx, :list, []), 1, 0)"
  end

  test "server and account scopes route to their store DSL ops" do
    src =
      gen!("""
      $server_var = 1;
      mes "" + #account_var;
      close;
      """)

    assert src =~ ~S{set_server_var(ctx, "server_var", 1)}
    assert src =~ ~S{get_account_var(ctx, "#account_var", 0)}
    refute src =~ "todo(:set_var"
    refute src =~ ~S{Todo.call!(:get_var}
  end

  test "On* labels wire to on_event/2 clauses; the macro derives events/0" do
    src =
      gen!(
        """
        mes "hi";
        close;

        OnInit:
        end;

        OnTimer1000:
        end;
        """,
        module: "Aesir.ZoneServer.Content.Npc.Payon.TestNpcOnEvents"
      )

    assert src =~ ~S|def on_event("OnInit", ctx), do: ev_oninit(ctx)|
    assert src =~ ~S|def on_event("OnTimer1000", ctx), do: ev_ontimer1000(ctx)|
    refute src =~ "unwired_events"

    [{module, _}] = Code.compile_string(src)
    assert module.events() == ["OnInit", "OnTimer1000"]
  end

  test "OnTouch_ normalizes to the OnTouch head the engine dispatches, deduping with OnTouch" do
    src =
      gen!(
        """
        mes "hi";
        close;

        OnTouch:
        end;

        OnTouch_:
        end;
        """,
        module: "Aesir.ZoneServer.Content.Npc.Payon.TestNpcOnTouchDedupe"
      )

    assert src =~ ~S|def on_event("OnTouch", ctx), do: ev_ontouch(ctx)|
    refute src =~ "OnTouch_"

    [{module, _}] = Code.compile_string(src)
    assert module.events() == ["OnTouch"]
  end

  test "npc session/event buildins map to DSL calls" do
    src =
      gen!("""
      donpcevent "Boss::OnDead";
      doevent "Boss::OnRespawn";
      initnpctimer;
      initnpctimer "Boss";
      stopnpctimer;
      stopnpctimer "Boss";
      npctalk "hi!";
      enablenpc "Boss";
      disablenpc "Boss";
      hideonnpc "Boss";
      hideoffnpc "Boss";
      close;
      """)

    assert src =~ ~S{|> donpcevent("Boss::OnDead")}
    assert src =~ ~S{|> doevent("Boss::OnRespawn")}
    assert src =~ "|> initnpctimer()"
    assert src =~ ~S{|> initnpctimer("Boss")}
    assert src =~ "|> stopnpctimer()"
    assert src =~ ~S{|> stopnpctimer("Boss")}
    assert src =~ ~S{|> npctalk("hi!")}
    assert src =~ ~S{|> enablenpc("Boss")}
    assert src =~ ~S{|> disablenpc("Boss")}
    assert src =~ ~S{|> hideonnpc("Boss")}
    assert src =~ ~S{|> hideoffnpc("Boss")}
    assert src =~ "|> close()"
  end

  test "getnpctimer type 0 reads elapsed ms; other types and arities stay stubs" do
    src =
      gen!("""
      if (getnpctimer(0) > 500) close;
      .@t = getnpctimer(0, "Boss");
      if (getnpctimer(1) > 0) close;
      npctalk "hi", 1;
      close;
      """)

    assert src =~ "getnpctimer(ctx) > 500"
    assert src =~ ~S{set_local(ctx, :t, getnpctimer(ctx, "Boss"))}
    assert src =~ ~S|Todo.call!(:getnpctimer, [1])|
    assert src =~ ~S|todo(:npctalk, ["hi", 1])|
  end

  test "monster maps onto summon_mob with map, coords, amount and event" do
    src =
      gen!("""
      monster "prontera",155,180,"Poring",1002,1;
      monster "prontera",0,0,"P",1002,5,"B::OnD";
      monster "this",10,20,"Poring",1002,1;
      monster "gefenia",-1,-1,"D",PORING,2,"B::OnD";
      close;
      """)

    assert src =~ ~S|summon_mob(mob_id: 1002, map: "prontera", at: {155, 180})|

    assert src =~
             ~S|summon_mob(mob_id: 1002, map: "prontera", at: :random, amount: 5, event: "B::OnD")|

    assert src =~ ~S|summon_mob(mob_id: 1002, at: {10, 20})|

    assert src =~
             ~S|summon_mob(mob_name: "PORING", map: "gefenia", at: :random, amount: 2, event: "B::OnD")|
  end

  test "monster case variant and dynamic args render; wrong arity stays a stub" do
    src =
      gen!("""
      Monster .@map$,.@x,.@y," ",1002,.@n,.@label$;
      monster "prontera",155,180;
      close;
      """)

    assert src =~ ~S|mob_id: 1002|
    assert src =~ ~S|map: get_local(ctx, :"map$", "")|
    assert src =~ ~S|at: {get_local(ctx, :x, 0), get_local(ctx, :y, 0)}|
    assert src =~ ~S|amount: get_local(ctx, :n, 0)|
    assert src =~ ~S|event: get_local(ctx, :"label$", "")|
    assert src =~ ~S|todo(:monster, ["prontera", 155, 180])|
  end

