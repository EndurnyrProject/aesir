  defmodule ScriptSession do
    use GenServer

    def start_link(test_pid), do: GenServer.start_link(__MODULE__, test_pid)

    @impl true
    def init(test_pid), do: {:ok, test_pid}

    @impl true
    def handle_call({:npc, {:script_apply, op}}, _from, test_pid) do
      send(test_pid, {:script_apply, op})
      {:reply, {:ok, :unchanged}, test_pid}
    end
  end

  defp function_index!(functions) do
    {:ok, index} = FunctionIndex.build(functions)
    index
  end

  defp gen!(body, opts \\ []) do
    opts =
      Map.merge(
        %{
          module: "Aesir.ZoneServer.Content.Npc.Payon.TestNpc",
          kind: :script,
          source: "test.txt:1",
          spawns: [%{map: "payon", x: 1, y: 2, dir: 3, sprite: 58, name: "Test"}],
          functions: %{}
        },
        Map.new(opts)
      )

    {:ok, src} = Codegen.generate(body, opts)
    assert {:ok, _} = Code.string_to_quoted(src)
    src
  end

  test "re-raises a cold item catalog error" do
    stub(Items, :loaded?, fn -> false end)
    reject(&Items.by_aegis/1)

    assert_raise CatalogNotLoadedError, fn -> gen!("getitem Red_Potion,1;") end
  end

