  test "while loop with plain body recurses; nested break uses throw" do
    plain =
      gen!("""
      while (.@i < 3) .@i++;
      close;
      """)

    assert plain =~ ~S{ctx |> loop_1() |> close()}
    assert plain =~ "defp loop_1(ctx) do"
    refute plain =~ "throw"

    thrown =
      gen!("""
      while (1) {
        if (.@i > 2) break;
        .@i++;
      }
      close;
      """)

    assert thrown =~ "throw({:brk_1, ctx})"
    assert thrown =~ ":throw, {:brk_1, ctx} -> {:done, ctx}"
    # `while (1)` has a constant-true guard: no dead `if true do … else ctx end`.
    refute thrown =~ "if true do"
  end

  test "a blocking loop condition re-evaluates inside the loop function" do
    looped =
      gen!("""
      while (select("Again:Stop") == 1) {
        mes "again";
      }
      close;
      """)

    assert looped =~ ~r/defp loop_1\(ctx\) do\s+\{ctx, v1\} = select\(ctx, \["Again", "Stop"\]\)/
    refute looped =~ "loop_with_blocking_condition"

    do_while =
      gen!("""
      do {
        mes "again";
      } while (select("Again:Stop") == 1);
      close;
      """)

    assert do_while =~ ~r/\{ctx, v1\} = .*select\(.*\["Again", "Stop"\]\)/
    assert do_while =~ "if v1 == 1 do"
    refute do_while =~ "loop_with_blocking_condition"
  end

