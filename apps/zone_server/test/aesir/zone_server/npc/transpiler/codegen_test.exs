  test "while loop with plain body recurses; nested break uses throw" do
    plain =
      gen!("""
      while (.@i < 3) .@i++;
      close;
      """)

    assert plain =~ ~S{ctx |> loop_1() |> close()}
    assert plain =~ "defp loop_1(ctx) do"
    refute plain =~ "throw"

    thrown =
      gen!("""
      while (1) {
        if (.@i > 2) break;
        .@i++;
      }
      close;
      """)

    assert thrown =~ "throw({:brk_1, ctx})"
    assert thrown =~ ":throw, {:brk_1, ctx} -> {:done, ctx}"
    # `while (1)` has a constant-true guard: no dead `if true do … else ctx end`.
    refute thrown =~ "if true do"
  end

  test "an all-stop switch with a nested break drops the dead ctx binding" do
    src =
      gen!("""
