    refute src =~ "todo(ctx, :mapannounce"
    refute src =~ "todo(ctx, :areaannounce"
    refute src =~ "todo(ctx, :broadcast"
  end

  test "rathena semantics: truthiness, bool_int, concat, bitwise" do
    src =
