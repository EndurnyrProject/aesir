    assert src =~ "get_rand_group_item(:ore, 2, 0)"
    assert src =~ "get_rand_group_item(:ore, 3, 1)"
    refute src =~ "todo(ctx, :getgroupitem"
    refute src =~ "todo(ctx, :getrandgroupitem"
