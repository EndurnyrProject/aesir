defmodule Aesir.Commons.Models.BossRespawn do
  @moduledoc """
  A durable shadow of a boss monster's in-memory respawn timer.

  A row exists only while a respawn is pending: written on boss death
  alongside the live `Process.send_after` timer, and deleted when the boss
  respawns. The in-memory timer is the live driver and this table is never
  consulted while the server is running; it exists solely so a restart does
  not silently reset a camped boss's deadline. At boot, pending rows are
  reconciled and consulted by each map's first spawn rather than acted on
  directly.

  Rows are matched to spawn configuration greedily by `mob_id` within
  `map_name`, never positionally, since spawn data is regenerated by an
  importer that can reorder entries. There is no foreign key to map or mob
  data: both are file-backed (`priv/db/*.yml`), not database rows.
  """

  use Ecto.Schema
  import Ecto.Changeset

  @type t :: %__MODULE__{
          id: integer() | nil,
          map_name: String.t() | nil,
          mob_id: integer() | nil,
          respawn_at: DateTime.t() | nil,
          inserted_at: NaiveDateTime.t() | nil
        }

  schema "boss_respawns" do
    field :map_name, :string
    field :mob_id, :integer
    field :respawn_at, :utc_datetime

    timestamps(updated_at: false)
  end

  @doc """
  Creates a changeset for a pending boss respawn deadline.
  """
  @spec changeset(t(), map()) :: Ecto.Changeset.t()
  def changeset(boss_respawn, attrs) do
    boss_respawn
    |> cast(attrs, [:map_name, :mob_id, :respawn_at])
    |> validate_required([:map_name, :mob_id, :respawn_at])
  end
end
